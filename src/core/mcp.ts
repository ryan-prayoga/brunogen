import path from "node:path";

import { writeTextFile } from "./fs";
import {
  buildToolInputSchema,
  listOpenApiOperations,
  openApiProjectMeta,
} from "./openapi-read";
import type { BrunogenConfig } from "./model";

export async function writeMcpServer(
  openApi: Record<string, unknown>,
  outputDirectory: string,
  config: BrunogenConfig,
): Promise<void> {
  const operations = listOpenApiOperations(openApi);
  const meta = openApiProjectMeta(openApi);
  const toolDefinitions = operations.map((operation) => ({
    name: operation.operationId,
    description: `${operation.method.toUpperCase()} ${operation.pathname} — ${operation.summary}`,
    method: operation.method.toUpperCase(),
    path: operation.pathname,
    inputSchema: buildToolInputSchema(operation),
    security: operation.security ?? [],
  }));

  await writeTextFile(
    path.join(outputDirectory, "package.json"),
    `${JSON.stringify({
      name: `${sanitizePackageName(meta.title)}-mcp`,
      version: "1.0.0",
      private: true,
      type: "module",
      description: `MCP server generated by brunogen for ${meta.title}`,
      scripts: {
        start: "node src/server.js",
        dev: "node --watch src/server.js",
      },
      dependencies: {
        "@modelcontextprotocol/sdk": "^1.12.1",
        zod: "^3.24.2",
      },
      engines: {
        node: ">=20",
      },
    }, null, 2)}\n`,
  );

  await writeTextFile(
    path.join(outputDirectory, "README.md"),
    renderMcpReadme(meta, config),
  );

  await writeTextFile(
    path.join(outputDirectory, "src", "server.js"),
    renderMcpServerSource(meta, toolDefinitions, config),
  );
}

